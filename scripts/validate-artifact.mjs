import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { Script } from 'node:vm';
const html=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
assert.match(html,/<title>Aion 2 · Progress Tracker<\/title>/);
assert.match(html,/href="\.\/favicon.svg"/);
assert.doesNotMatch(html,/\/api\/state|__DATA__/);
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
new Script(scripts[0][1]);
assert.ok((await stat(new URL('../dist/favicon.svg',import.meta.url))).isFile());
assert.ok((await stat(new URL('../dist/.nojekyll',import.meta.url))).isFile());
console.log('Validated static Pages artifact, relative assets and JavaScript syntax.');
